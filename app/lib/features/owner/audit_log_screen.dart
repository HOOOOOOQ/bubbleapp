import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:intl/intl.dart';

import '../../state/providers.dart';
import '../../widgets/common.dart';

class AuditLogScreen extends ConsumerStatefulWidget {
  const AuditLogScreen({super.key});
  @override
  ConsumerState<AuditLogScreen> createState() => _AuditLogScreenState();
}

class _AuditLogScreenState extends ConsumerState<AuditLogScreen> {
  final _query = TextEditingController();
  String _source = 'all'; // all, admin, owner

  Future<List<Map<String, dynamic>>> _load() async {
    if (_source == 'owner') return ref.read(repositoryProvider).ownerAuditLog(limit: 100);
    if (_source == 'admin') return ref.read(repositoryProvider).adminAuditLog(limit: 100);
    final a = await ref.read(repositoryProvider).adminAuditLog(limit: 50);
    final o = await ref.read(repositoryProvider).ownerAuditLog(limit: 50);
    final merged = [...a, ...o]..sort((x, y) => (y['created_at'] as String).compareTo(x['created_at'] as String));
    return merged.take(100).toList();
  }

  @override
  Widget build(BuildContext context) {
    final access = ref.watch(accessProvider).valueOrNull ?? AccessSnapshot.empty;
    if (!access.can('audit.read') && !access.isOwner) {
      return const BubblePage(title: 'Audit logs', child: EmptyState(message: 'Audit access required.', icon: Icons.lock_outline));
    }
    return BubblePage(
      title: 'Audit logs',
      child: Column(children: [
        Padding(
          padding: const EdgeInsets.all(12),
          child: Row(children: [
            Expanded(child: TextField(controller: _query, decoration: const InputDecoration(labelText: 'Search action, target, actor'), onSubmitted: (_) => setState(() {}))),
            const SizedBox(width: 8),
            DropdownButton<String>(value: _source, items: const [DropdownMenuItem(value: 'all', child: Text('All')), DropdownMenuItem(value: 'admin', child: Text('Admin')), DropdownMenuItem(value: 'owner', child: Text('Owner'))], onChanged: (v) => setState(() => _source = v!)),
            IconButton(onPressed: () => setState(() {}), icon: const Icon(Icons.search)),
          ]),
        ),
        Expanded(
          child: FutureBuilder<List<Map<String, dynamic>>>(
            future: _load(),
            builder: (context, snap) {
              if (snap.connectionState != ConnectionState.done) return const Center(child: CircularProgressIndicator());
              if (snap.hasError) return ErrorView(error: snap.error!);
              var list = snap.data ?? [];
              final q = _query.text.trim().toLowerCase();
              if (q.isNotEmpty) list = list.where((r) => '${r['action']} ${r['target_type']} ${r['target_id']} ${r['actor_id']}'.toLowerCase().contains(q)).toList();
              if (list.isEmpty) return const EmptyState(message: 'No audit entries match.');
              return ListView.separated(
                padding: const EdgeInsets.all(12),
                itemCount: list.length,
                separatorBuilder: (_, __) => const SizedBox(height: 8),
                itemBuilder: (context, i) {
                  final r = list[i];
                  return GlassCard(
                    padding: const EdgeInsets.all(12),
                    child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                      Row(children: [Expanded(child: Text(r['action'] ?? '', style: const TextStyle(fontWeight: FontWeight.w700, fontSize: 13))), StatusBadge(label: r['target_type'] ?? '')]),
                      if (r['target_id'] != null) Text('Target: ${r['target_id']}', style: Theme.of(context).textTheme.bodySmall),
                      if (r['actor_id'] != null) Text('Actor: ${r['actor_id']}', style: Theme.of(context).textTheme.bodySmall),
                      if (r['metadata'] != null) Text('${r['metadata']}', maxLines: 3, overflow: TextOverflow.ellipsis, style: Theme.of(context).textTheme.labelSmall),
                      Text(r['created_at'] != null ? DateFormat.yMMMd().add_Hm().format(DateTime.parse(r['created_at'] as String).toLocal()) : '', style: Theme.of(context).textTheme.labelSmall),
                      Text('Immutable — updates/deletes rejected by trigger (42501). Generated by SECURITY DEFINER write_audit().', style: Theme.of(context).textTheme.labelSmall?.copyWith(color: Theme.of(context).colorScheme.onSurfaceVariant)),
                    ]),
                  );
                },
              );
            },
          ),
        ),
      ]),
    );
  }
}

